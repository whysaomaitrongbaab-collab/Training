# -*- coding: utf-8 -*-
"""เสียงบอกเหตุ — ให้เดินออกจากจอไปทำอย่างอื่นได้ระหว่างรอ

ทำไมต้องมี: ขั้นที่ต้องรอในระบบนี้ยาวทั้งคู่ — เปิดการ์ด+โหลดโมเดล 20-45 นาที
และถอดแบบหนึ่งงาน 30-60 นาที · ที่ผ่านมาต้องนั่งจ้อง terminal เพราะถ้าไม่เห็น
บรรทัด READY ตอนมันขึ้น มันก็จะเลื่อนหายไปใน log แล้วไม่รู้ว่าเสร็จตั้งแต่เมื่อไหร่

ใช้ winsound ของ Python เอง ไม่ต้องลงอะไรเพิ่ม · เครื่องที่ไม่ใช่ Windows หรือการ์ดเสียง
มีปัญหา จะถอยไปใช้ terminal bell เงียบๆ ไม่มีวันทำให้โปรแกรมหลักล้ม

ปิดเสียง (เช่นตอนขึ้นเวทีจริง ไมค์อาจรับเสียงไปด้วย):
    set PURSON_QUIET=1
"""
import os
import sys

# (ความถี่ Hz, ความยาว ms) — ตั้งใจให้สามเสียงแยกออกจากกันได้จากอีกห้อง
#   ready = ไล่ขึ้น C-E-G ฟังแล้วรู้ว่า "มาได้แล้ว"
#   done  = สองเสียงสั้นสูง "งานหนึ่งจบ"
#   fail  = สองเสียงต่ำไล่ลง ฟังแล้วรู้ทันทีว่าไม่ใช่ข่าวดี
TUNES = {
    "ready": [(523, 160), (659, 160), (784, 320)],
    "done":  [(784, 130), (1047, 260)],
    "fail":  [(420, 260), (300, 420)],
}


def _play(name):
    if os.environ.get("PURSON_QUIET"):
        return
    try:
        import winsound
        for freq, ms in TUNES[name]:
            winsound.Beep(freq, ms)
    except Exception:
        # ไม่ใช่ Windows / ไม่มีลำโพง / winsound โยน RuntimeError — ห้ามทำให้งานหลักล้ม
        # เพราะเรื่องเสียง มันเป็นของแถม ไม่ใช่ของจำเป็น
        try:
            sys.stdout.write("\a")
            sys.stdout.flush()
        except Exception:
            pass


def ready():
    """โมเดลพร้อมรับงานแล้ว — จังหวะที่รอนานสุด (20-45 นาที)"""
    _play("ready")


def done():
    """งานถอดแบบหนึ่งงานจบ"""
    _play("done")


def fail():
    """มีอะไรล้มจนต้องมาดู — เสียงต่างจากสองอันบน ไม่ต้องเดินมาดูจอถึงจะรู้"""
    _play("fail")


if __name__ == "__main__":
    # ฟังเทียบสามเสียง: python notify.py
    for n in ("ready", "done", "fail"):
        print(f"  {n} ...", flush=True)
        _play(n)
    print("ถ้าไม่ได้ยินเลย: เช็คลำโพง หรือ PURSON_QUIET ถูกตั้งไว้อยู่"
          f" (ตอนนี้={os.environ.get('PURSON_QUIET') or 'ไม่ได้ตั้ง'})")
